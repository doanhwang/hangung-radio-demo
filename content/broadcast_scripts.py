def get_all_segments():
    """모든 방송 구간을 플랫한 리스트로 반환"""
    segments = []
    for prog_id, prog in PROGRAMS.items():
        for ep in prog["episodes"]:
            ep_id = ep["ep"]
            for seg_key, text in ep["segments"].items():
                seg_num = seg_key.split("_")[0]  # S1, S2, S3, S4, S5
                segments.append({
                    "program_id": prog_id,
                    "program_name": prog["name"],
                    "episode_id": ep_id,
                    "episode_title": ep.get("title", ""),
                    "segment_key": seg_key,
                    "segment_num": seg_num,
                    "text": text,
                    "filename": f"HANGUNG_{prog_id}_{ep_id}_{seg_num}_20260606_v1.mp3"
                })
    return segments


